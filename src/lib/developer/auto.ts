import 'server-only';
import { loadDeveloperClient } from './clients';
import { buildPromptContext } from './context';
import { AUTO_BY } from './auto-status';
import { generateDesignProposals, generateReferenceSpec } from './generate';
import { defaultReferences, PROPOSALS } from './messages';
import { clientChoices, isClientSource } from './reference-sources';
import { referenceSpecsReady } from './reference-specs';
import { developerSchemaReady, loadProject, loadPrompts } from './store';

/**
 * Runs after the client confirms the onboarding form: writes both design prompts, so they are
 * ready on the Design tab when the team opens it. Proposal 1 and 2 follow the client's two
 * design examples, in the form's order. For an example that is the client's own website or
 * pictures, its reference spec is written first, exactly as the Design tab's button does.
 *
 * Never overwrites anything: a client who already has design prompts, or an approved design,
 * is left alone. Failures are logged; the team can still generate on the Design tab.
 */
export async function autoGenerateDesigns(leadId: string): Promise<{ ok: boolean; skipped?: string; error?: string }> {
  if (!(await developerSchemaReady())) return { ok: false, skipped: 'developer tables missing' };
  const client = await loadDeveloperClient(leadId);
  if (!client?.onboarding) return { ok: false, skipped: 'no onboarding form' };
  const [project, existing] = await Promise.all([loadProject(leadId), loadPrompts(leadId, 'design')]);
  if (project.approved_version_id) return { ok: false, skipped: 'design already approved' };
  if (existing.length) return { ok: false, skipped: 'design prompts already exist' };

  const context = await buildPromptContext(client.lead, client.onboarding.id);
  if (!context) return { ok: false, skipped: 'form not found' };
  const specsReady = await referenceSpecsReady();
  // The client's own sources only when they can be read (a link, or pictures the model can see).
  const usable = new Set(clientChoices(context.clientReferences, context.referenceShots).map((c) => c.value));
  const references = defaultReferences(context.examples, (value) => !isClientSource(value) || (specsReady && usable.has(value)));

  // The client's own references need their spec before the prompt that follows them. Side by
  // side: reading two websites one after the other could take longer than the function may run.
  const own = [...new Set(PROPOSALS.map((p) => references[p]).filter((v): v is string => !!v && isClientSource(v)))];
  await Promise.all(
    own.map(async (value) => {
      const spec = await generateReferenceSpec(leadId, value, false, AUTO_BY);
      // Without a spec the prompt still works from what the client wrote about the reference.
      if (!spec.ok) console.error(`[developer/auto] spec for ${value} of ${leadId} failed: ${spec.error}`);
    }),
  );

  // Someone may have generated by hand while the specs were written.
  if ((await loadPrompts(leadId, 'design')).length) return { ok: false, skipped: 'design prompts already exist' };
  const result = await generateDesignProposals(leadId, references, AUTO_BY);
  if (!result.ok) {
    console.error(`[developer/auto] design prompts for ${leadId} failed: ${result.error}`);
    return { ok: false, error: result.error };
  }
  return { ok: true };
}
